import pandas as pd, numpy as np
pd.set_option('display.width',250); pd.set_option('display.max_columns',50); pd.set_option('display.max_colwidth',50)
u=pd.read_csv('df_Uid_data_hack.csv',sep=';',dtype=str,keep_default_na=False)
f=pd.read_csv('df_Fid_Uid_link_hack.csv',sep=';',dtype=str,keep_default_na=False)
p=pd.read_csv('df_Uid_payment_hack.csv',sep=';',dtype={'BENEFICIARY':str,'PAYER':str})
U=set(u.SYNTHETIC_U)
print('### U_428697'); print(u[u.SYNTHETIC_U=='U_428697'][['OKFS_NAME','MAINOKVED_CODE','REVENUE_COMPANY','GROUP_ID','CITY','CL_TYPE','AMOUNT_WORKERS_FNS_GRADATION']].to_string())
print('in payments as payer/benef:',(p.PAYER=='U_428697').sum(),(p.BENEFICIARY=='U_428697').sum(),' in links:',(f.SYNTHETIC_U=='U_428697').sum())
u['rev']=u.REVENUE_COMPANY.astype(float)
print('### group revenue (dedup U)'); ud=u.drop_duplicates('SYNTHETIC_U')
gr=ud.groupby('GROUP_ID').rev.sum(); print('groups >=15e9:',(gr>=15e9).sum(),' companies in them:',ud.GROUP_ID.isin(gr[gr>=15e9].index).sum())
print('companies >=15e9 by CL_TYPE:'); print(ud[ud.rev>=15e9].CL_TYPE.value_counts())
print('companies >=15e9 top okved2:'); print(ud[ud.rev>=15e9].MAINOKVED_CODE.str[:2].value_counts().head(10).to_string())
print('### links')
print('link U in data:',f.SYNTHETIC_U.isin(U).mean().round(4),' missing:',(~f.SYNTHETIC_U.isin(U)).sum())
print('dup (F,U) pairs:',f.duplicated(['SYNTHETIC_F','SYNTHETIC_U']).sum())
fc=f.groupby('SYNTHETIC_F').SYNTHETIC_U.nunique(); print('F linked to >=2 U:',(fc>=2).sum(),' max:',fc.max())
fr=f.groupby('SYNTHETIC_F')[['CITY_NAME','RC_NAME']].nunique(); print('F with >1 city:',(fr.CITY_NAME>1).sum())
print('companies with any F:',f.SYNTHETIC_U.nunique(),' share of data:',round(f.SYNTHETIC_U.isin(U).sum()/len(U),4))
print('RC_NAME:'); print(f.RC_NAME.replace('','<EMPTY>').value_counts().to_string())
print('odd city names:', [c for c in f.CITY_NAME.unique() if '"' in c or 'Мск' in c][:20])
# shared-person company pairs
ff=f[f.SYNTHETIC_F.isin(fc[fc>=2].index)]
m=ff.merge(ff,on='SYNTHETIC_F'); m=m[m.SYNTHETIC_U_x<m.SYNTHETIC_U_y]
print('shared-person company pairs:',m[['SYNTHETIC_U_x','SYNTHETIC_U_y']].drop_duplicates().shape[0])
gm=u.drop_duplicates('SYNTHETIC_U').set_index('SYNTHETIC_U').GROUP_ID
pp=m[['SYNTHETIC_U_x','SYNTHETIC_U_y']].drop_duplicates()
pp=pp[pp.SYNTHETIC_U_x.isin(U)&pp.SYNTHETIC_U_y.isin(U)]
print('  of which same GROUP_ID:',(gm.loc[pp.SYNTHETIC_U_x].values==gm.loc[pp.SYNTHETIC_U_y].values).mean().round(3))
print('### payments')
print(p.dtypes); print('PAY_AMT describe:'); print(p.PAY_AMT.describe(percentiles=[.01,.25,.5,.75,.99]).apply(lambda x:f'{x:,.2f}'))
print('PAY_CNT describe:'); print(p.PAY_CNT.describe().apply(lambda x:f'{x:,.2f}'))
print('amt<=0:',(p.PAY_AMT<=0).sum(),' cnt<=0:',(p.PAY_CNT<=0).sum(),' na:',p.isna().sum().to_dict())
print('amt mult of 1000:',(p.PAY_AMT%1000==0).mean().round(4),' mult of 1e6:',(p.PAY_AMT%1e6==0).mean().round(4))
print('self payments:',(p.PAYER==p.BENEFICIARY).sum())
print('dup (payer,benef) pairs:',p.duplicated(['PAYER','BENEFICIARY']).sum(),' full dup rows:',p.duplicated().sum())
print('payer in data:',p.PAYER.isin(U).mean().round(4),' benef in data:',p.BENEFICIARY.isin(U).mean().round(4))
print('both in data:',(p.PAYER.isin(U)&p.BENEFICIARY.isin(U)).mean().round(4),' neither:',(~p.PAYER.isin(U)&~p.BENEFICIARY.isin(U)).mean().round(4))
print('id formats:',p.PAYER.str.replace(r'\d+','N',regex=True).value_counts().to_dict(),p.BENEFICIARY.str.replace(r'\d+','N',regex=True).value_counts().to_dict())
print('data companies w/ any payment:',ud.SYNTHETIC_U.isin(set(p.PAYER)|set(p.BENEFICIARY)).mean().round(4))
print('  as payer:',ud.SYNTHETIC_U.isin(set(p.PAYER)).mean().round(4),' as benef:',ud.SYNTHETIC_U.isin(set(p.BENEFICIARY)).mean().round(4))
avg=p.PAY_AMT/p.PAY_CNT; print('avg ticket median:',f'{avg.median():,.0f}')
# turnover vs revenue sanity
inc=p.groupby('BENEFICIARY').PAY_AMT.sum(); out=p.groupby('PAYER').PAY_AMT.sum()
x=ud.set_index('SYNTHETIC_U').rev.to_frame().join(inc.rename('inc')).dropna()
print('incoming/revenue ratio median:',(x.inc/x.rev).median().round(4),' p90:',(x.inc/x.rev).quantile(.9).round(3), ' n=',len(x))
# concentration
g=p[p.BENEFICIARY.isin(U)].groupby('BENEFICIARY').PAY_AMT; top=g.max()/g.sum(); n=g.size()
print('incoming top-1 share median:',top.median().round(3),' share>=0.5:',(top>=0.5).mean().round(3),' cnt-partners median:',n.median())
print('companies >=15e9: with payments:',ud[ud.rev>=15e9].SYNTHETIC_U.isin(set(p.PAYER)|set(p.BENEFICIARY)).sum(),' with F links:',ud[ud.rev>=15e9].SYNTHETIC_U.isin(set(f.SYNTHETIC_U)).sum())
