import pandas as pd
pd.set_option('display.width',250); pd.set_option('display.max_columns',50); pd.set_option('display.max_colwidth',80)
u=pd.read_csv('df_Uid_data_hack.csv',sep=';',dtype=str,keep_default_na=False)
f=pd.read_csv('df_Fid_Uid_link_hack.csv',sep=';',dtype=str,keep_default_na=False)
p=pd.read_csv('df_Uid_payment_hack.csv',sep=';',dtype=str,keep_default_na=False)
print('### dup SYNTHETIC_U')
d=u[u.SYNTHETIC_U.duplicated(keep=False)].sort_values('SYNTHETIC_U')
print(len(d), d.SYNTHETIC_U.nunique())
for k,g in d.groupby('SYNTHETIC_U'):
    diff=[c for c in g.columns if g[c].nunique()>1]; print(k,len(g),'differs in',diff)
print('### categorical value counts')
for c in ['OKFS_NAME','COMPANY_AGE_YEARS_GRADATION','ECO_MARK_LABEL','NEGATIVEMARK','AMOUNT_WORKERS_FNS_GRADATION','AMOUNT_WORKERS_SPARK_GRADATION','CL_TYPE','CL_PRODUCT_RKO_MARK','CL_PRODUCT_GAR_MARK','CL_PRODUCT_LOA_MARK','CL_PRODUCT_LEA_MARK','CL_PRODUCT_DEP_MARK','CL_PRODUCT_ZPP_MARK','FTS_FLAG','FACTORING_MARK']:
    print('--',c); print(u[c].replace('','<EMPTY>').value_counts().to_string())
print('### revenue')
r=pd.to_numeric(u.REVENUE_COMPANY,errors='coerce'); print('nonnumeric',r.isna().sum())
print(r.describe(percentiles=[.01,.05,.1,.25,.5,.75,.9,.95,.99]).apply(lambda x:f'{x:,.0f}'))
print('<=0:',(r<=0).sum(),' >=15e9:',(r>=15e9).sum(),' >=15e6:',(r>=15e6).sum(), ' >=15e3(thous?):',(r>=15e6/1000).sum())
print('non-integer:',(r%1!=0).sum(), ' mult of 1000:',(r%1000==0).mean().round(3))
print('### revenue by CL_TYPE median'); print(u.assign(r=r).groupby('CL_TYPE').r.median().apply(lambda x:f'{x:,.0f}'))
print('### FTS consistency')
print(pd.crosstab(u.FTS_FLAG, u.FTS_COUNTRY_NAME!=''))
cs=u.FTS_COUNTRY_NAME[u.FTS_COUNTRY_NAME!=''].str.split(r',\s*').explode().str.strip()
print('distinct countries:',cs.nunique()); print(cs.value_counts().head(25).to_string())
print('max countries per company:',u.FTS_COUNTRY_NAME[u.FTS_COUNTRY_NAME!=''].str.count(',').max()+1)
print('### FNS vs SPARK where both')
b=u[u.AMOUNT_WORKERS_SPARK_GRADATION!='']; print(len(b)); print(pd.crosstab(b.AMOUNT_WORKERS_FNS_GRADATION,b.AMOUNT_WORKERS_SPARK_GRADATION))
print('### OKVED')
codes=u.MAINOKVED_CODE; print('formats:',codes.str.replace(r'\d','9',regex=True).value_counts().to_string())
cn=u.groupby('MAINOKVED_CODE').MAINOKVED_NAME.nunique(); print('codes w/ >1 name:',(cn>1).sum(), cn[cn>1].index.tolist()[:10])
nc=u.groupby('MAINOKVED_NAME').MAINOKVED_CODE.nunique(); print('names w/ >1 code:',(nc>1).sum(), nc[nc>1].index.tolist()[:5])
print('top 2-digit:'); print(codes.str[:2].value_counts().head(20).to_string())
print('### geo'); print(u.REGION.value_counts().head(15).to_string())
cr=u.groupby('CITY').REGION.nunique(); print('cities in >1 region:',(cr>1).sum(), cr[cr>1].index.tolist()[:10])
print('### groups'); gs=u.groupby('GROUP_ID').size(); print(gs.describe()); print('groups size1:',(gs==1).sum(),' size>=2:',(gs>=2).sum(),' max:',gs.max(), gs.idxmax())
print('GROUP_ID formats:',u.GROUP_ID.str.replace(r'\d+','N',regex=True).value_counts().to_string())
print('### NEGATIVEMARK x CL_TYPE'); print(pd.crosstab(u.NEGATIVEMARK,u.CL_TYPE))
print('### products x CL_TYPE (mean)'); print(u.assign(**{c:u[c].astype(float) for c in u.columns if 'MARK' in c and c!='ECO_MARK_LABEL'}).groupby('CL_TYPE')[[c for c in u.columns if ('PRODUCT' in c or c=='FACTORING_MARK')]].mean().round(3).T)
