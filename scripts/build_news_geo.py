def country_patterns(name: str) -> list[str]:
    if name in COUNTRY_MANUAL:
        return COUNTRY_MANUAL[name]
    w = name.lower()
    parts = w.split()
    if len(parts) > 1:
        return [r"\s+".join(f"{p[:-1] if p.endswith(('я', 'а', 'ь')) else p}\\w*" for p in parts)]
    if w.endswith("ия"):
        return [f"(?<![а-я]){w[:-2]}и(?:я|и|ю|ей){NL}"]
    if w.endswith(("а", "я")):
        return [f"(?<![а-я]){w[:-1]}(?:а|я|ы|и|е|у|ю|ой|ей){NL}"]
    if w.endswith("ь"):
        return [f"(?<![а-я]){w[:-1]}(?:ь|я|и|ю|ем|е|ью){NL}"]
    if w.endswith("ы"):
        return [f"(?<![а-я]){w[:-1]}(?:ы|ов|ам|ах){NL}"]
    return [f"(?<![а-я]){w}(?:а|у|е|ом|ы)?{NL}"]


def region_patterns(name: str) -> list[str]:
    if name in REGION_MANUAL:
        return REGION_MANUAL[name]
    base = re.sub(r"\s*\((?:Республика|Адыгея|Якутия)\)", "", name)
    base = re.sub(r"^(Республика|Чувашская Республика-)\s*", "", base).strip()
    m = re.match(r"^(\w+?)(ская|ский|ское|ой|ый|ая)\s+(область|край)$", base)
    if m:                                   # «Амурская область» -> амурск; «Пензенская» -> пензенск
        return [m.group(1).lower() + "ск"]
    w = base.lower().split()[0]
    if w.endswith("ия"):
        return [f"(?<![а-я]){w[:-2]}и(?:я|и|ю|ей){NL}"]
    return [f"(?<![а-я]){w[:-1] if w.endswith(('а', 'я')) else w}\\w*"]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-dir", required=True)
    a = ap.parse_args()
    c = pd.read_csv(Path(a.data_dir) / "df_Uid_data_hack.csv", sep=";", dtype=str)
    toks: dict[str, int] = {}
    for v in c["FTS_COUNTRY_NAME"].dropna():
        for t in v.split(","):
            toks[t.strip()] = toks.get(t.strip(), 0) + 1
    countries = [{"name": n, "companies": k, "patterns": country_patterns(n)} for n, k in sorted(toks.items(), key=lambda x: -x[1])]
    regs = sorted(c["REGION"].dropna().unique().tolist())
    regions = [{"name": n, "companies": int((c["REGION"] == n).sum()), "patterns": region_patterns(n)} for n in regs]
    names = set(regs)
    for g, (_, members) in GROUPS.items():
        bad = [m for m in members if m not in names]
        assert not bad, (g, bad)
    groups = [{"name": g, "patterns": p, "regions": m} for g, (p, m) in GROUPS.items()]
    hdr = "# СГЕНЕРИРОВАНО scripts/build_news_geo.py из данных кейса (df_Uid_data_hack.csv). Не править вручную — менять скрипт.\n"
    (OUT / "geo_countries.yaml").write_text(hdr + yaml.safe_dump({"version": 1, "countries": countries}, allow_unicode=True, sort_keys=False, width=200), encoding="utf-8")
    (OUT / "geo_regions.yaml").write_text(hdr + yaml.safe_dump({"version": 1, "regions": regions, "groups": groups}, allow_unicode=True, sort_keys=False, width=200), encoding="utf-8")
    print(len(countries), "стран,", len(regions), "регионов,", len(groups), "групп")


if __name__ == "__main__":
    main()
